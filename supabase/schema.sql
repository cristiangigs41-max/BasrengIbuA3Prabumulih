  perform a3_admin();
  return coalesce((select jsonb_agg(a3_user_json(p) || jsonb_build_object('created_at', p.created_at,
            'orders_count', (select count(*) from orders o where o.user_id = p.id)) order by p.created_at desc)
          from profiles p where p.role = 'customer'), '[]'::jsonb);
end $$;

create or replace function a3_admin_report(p_from date, p_to date) returns jsonb
language plpgsql stable security definer set search_path = public as $$
declare l jsonb; t bigint; c int;
begin
  perform a3_admin();
  select coalesce(jsonb_agg(a3_order_json(o) order by o.id desc), '[]'::jsonb), coalesce(sum(o.total), 0), count(*)
    into l, t, c from orders o
   where o.status = 'Selesai' and (o.created_at at time zone 'Asia/Jakarta')::date between p_from and p_to;
  return jsonb_build_object('count', c, 'total', t, 'orders', l);
end $$;

