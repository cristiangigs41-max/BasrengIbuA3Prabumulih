-- ---------- Tabel ----------
create table if not exists profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  name text not null,
  email text not null,
  phone text,
  role text not null default 'customer' check (role in ('admin','customer')),
  created_at timestamptz not null default now()
);
create table if not exists categories (
  id bigint generated by default as identity primary key,
  name text not null,
  slug text not null unique
);
create table if not exists products (
  id bigint generated by default as identity primary key,
  category_id bigint not null references categories(id),
  name text not null,
  description text not null default '',
  image text,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
create table if not exists product_sizes (
  id bigint generated by default as identity primary key,
  product_id bigint not null references products(id) on delete cascade,
  label text not null,
  price integer not null check (price >= 0),
  stock integer not null default 0 check (stock >= 0)
);
create table if not exists cart_items (
  id bigint generated by default as identity primary key,
  user_id uuid not null references profiles(id) on delete cascade,
  product_size_id bigint not null references product_sizes(id) on delete cascade,
  flavor text not null,
  qty integer not null check (qty > 0),
  unique (user_id, product_size_id, flavor)
);
create table if not exists orders (
  id bigint generated by default as identity primary key,
  code text unique,
  user_id uuid not null references profiles(id),
  phone text,
  address text not null,
  status text not null default 'Pending' check (status in ('Pending','Diproses','Dikirim','Selesai','Dibatalkan')),
  total bigint not null,
  payment_method text not null,
  payment_status text not null default 'Belum Dibayar' check (payment_status in ('Belum Dibayar','Dibayar')),
  proof text,
  delivery_proof text,
  latitude double precision,
  longitude double precision,
  created_at timestamptz not null default now()
);
create table if not exists order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references orders(id) on delete cascade,
  product_size_id bigint references product_sizes(id) on delete set null,
  product_name text not null,
  size_label text not null,
  flavor text not null,
  qty integer not null,
  price integer not null,
  subtotal bigint not null
);
create index if not exists orders_user_idx on orders(user_id);
create index if not exists order_items_order_idx on order_items(order_id);

