create or replace function a3_checkout(p_phone text, p_address text, p_method text, p_proof text default null,
                                       p_lat double precision default null, p_lng double precision default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare u uuid := a3_uid(); oid bigint; sum_ bigint := 0; r record; s product_sizes; o orders; n integer := 0;
begin
  if length(trim(coalesce(p_address, ''))) < 10 then perform a3_err('Alamat minimal 10 karakter.'); end if;
  if p_method is null or length(p_method) > 40 then perform a3_err('Metode pembayaran tidak valid.'); end if;
  if p_method <> 'COD (Bayar di Tempat)' and coalesce(p_proof, '') = '' then perform a3_err('Bukti pembayaran wajib diunggah.'); end if;
  if p_lat is not null and p_lng is not null and not (p_lat between -3.56 and -3.30 and p_lng between 104.08 and 104.38) then
    perform a3_err('Lokasi antar harus berada di Kota Prabumulih, Sumatera Selatan.');
  end if;
  select count(*), coalesce(sum(ps.price::bigint * c.qty), 0) into n, sum_
    from cart_items c join product_sizes ps on ps.id = c.product_size_id where c.user_id = u;
  if n = 0 then perform a3_err('Keranjang kosong.'); end if;
  if sum_ < 20000 then perform a3_err('Minimum belanja Rp20.000.'); end if;
  sum_ := 0; n := 0;
  insert into orders (user_id, phone, address, total, payment_method, proof, latitude, longitude)
  values (u, left(p_phone, 20), trim(p_address), 0, p_method, case when p_method = 'COD (Bayar di Tempat)' then null else p_proof end, p_lat, p_lng)
  returning id into oid;
  for r in select c.* from cart_items c where c.user_id = u order by c.id loop
    n := n + 1;
    select * into s from product_sizes where id = r.product_size_id for update;
    if not found or not (select is_active from products where id = s.product_id) then perform a3_err('Ada produk yang sudah tidak tersedia.'); end if;
    if s.stock < r.qty then
      perform a3_err('Stok ' || (select name from products where id = s.product_id) || ' ' || s.label || ' tidak cukup.');
    end if;
    update product_sizes set stock = stock - r.qty where id = s.id;
    insert into order_items (order_id, product_size_id, product_name, size_label, flavor, qty, price, subtotal)
    values (oid, s.id, (select name from products where id = s.product_id), s.label, r.flavor, r.qty, s.price, s.price::bigint * r.qty);
    sum_ := sum_ + s.price::bigint * r.qty;
  end loop;
  if n = 0 then perform a3_err('Keranjang kosong.'); end if;
  if sum_ < 20000 then perform a3_err('Minimum belanja Rp20.000.'); end if;
  update orders set total = sum_, code = 'A3-' || lpad(oid::text, 4, '0') where id = oid returning * into o;
  delete from cart_items where user_id = u;
  return a3_order_json(o);
end $$;

create or replace function a3_orders() returns jsonb language plpgsql stable security definer set search_path = public as $$
declare u uuid := a3_uid();
begin
  return coalesce((select jsonb_agg(a3_order_json(o) order by o.id desc) from orders o where o.user_id = u), '[]'::jsonb);
end $$;

create or replace function a3_delivery_proof(p_order bigint, p_proof text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare u uuid := a3_uid(); o orders;
begin
  select * into o from orders where id = p_order and user_id = u;
  if not found then perform a3_err('Pesanan tidak ditemukan.'); end if;
  if o.status <> 'Dikirim' then perform a3_err('Bukti bayar ke pengantar bisa diunggah saat pesanan sedang dikirim.'); end if;
  if coalesce(p_proof, '') = '' then perform a3_err('Pilih foto bukti pembayaran.'); end if;
  update orders set delivery_proof = p_proof where id = p_order returning * into o;
  return a3_order_json(o);
end $$;

