create or replace function a3_products() returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'flavors', to_jsonb(a3_flavors()),
    'categories', coalesce((select jsonb_agg(jsonb_build_object('id', c.id, 'name', c.name, 'slug', c.slug) order by c.id) from categories c), '[]'::jsonb),
    'products', coalesce((select jsonb_agg(jsonb_build_object(
        'id', p.id, 'category_id', p.category_id, 'name', p.name, 'description', p.description, 'image', p.image,
        'is_active', p.is_active, 'category', (select c.slug from categories c where c.id = p.category_id),
        'sizes', coalesce((select jsonb_agg(jsonb_build_object('id', s.id, 'product_id', s.product_id, 'label', s.label, 'price', s.price, 'stock', s.stock) order by s.id)
                           from product_sizes s where s.product_id = p.id), '[]'::jsonb)) order by p.id)
      from products p), '[]'::jsonb))
$$;

