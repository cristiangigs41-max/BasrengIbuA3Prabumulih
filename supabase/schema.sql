create or replace function a3_admin_category_save(p_id bigint, p_name text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare slug_ text; r categories;
begin
  perform a3_admin();
  if length(trim(coalesce(p_name, ''))) = 0 then perform a3_err('Nama wajib diisi.'); end if;
  slug_ := trim(both '-' from regexp_replace(lower(trim(p_name)), '[^a-z0-9]+', '-', 'g'));
  if slug_ = '' then slug_ := 'kategori'; end if;
  if p_id is null then
    insert into categories (name, slug) values (trim(p_name), slug_) returning * into r;
  else
    update categories set name = trim(p_name), slug = slug_ where id = p_id returning * into r;
  end if;
  return to_jsonb(r);
exception when unique_violation then
  raise exception 'Nama kategori sudah dipakai.' using errcode = 'P0001';
end $$;

create or replace function a3_admin_category_del(p_id bigint) returns jsonb
language plpgsql security definer set search_path = public as $$
begin
  perform a3_admin();
  if exists (select 1 from products where category_id = p_id) then perform a3_err('Kategori masih memiliki produk.'); end if;
  delete from categories where id = p_id;
  return jsonb_build_object('message', 'ok');
end $$;

create or replace function a3_admin_product_save(p_id bigint, p_name text, p_desc text, p_cat bigint, p_active boolean, p_image text default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare pid bigint;
begin
  perform a3_admin();
  if length(trim(coalesce(p_name, ''))) = 0 then perform a3_err('Nama produk wajib diisi.'); end if;
  if not exists (select 1 from categories where id = p_cat) then perform a3_err('Kategori tidak valid.'); end if;
  if p_id is null then
    insert into products (category_id, name, description, image, is_active) values (p_cat, trim(p_name), coalesce(p_desc, ''), p_image, coalesce(p_active, true)) returning id into pid;
    insert into product_sizes (product_id, label, price, stock)
      values (pid, 'Pack 5K', 5000, 0), (pid, 'Pack 10K', 10000, 0), (pid, '1/2 Kg', 45000, 0), (pid, '1 Kg', 90000, 0);
  else
    update products set category_id = p_cat, name = trim(p_name), description = coalesce(p_desc, ''), is_active = coalesce(p_active, true),
           image = coalesce(p_image, image) where id = p_id returning id into pid;
    if pid is null then perform a3_err('Produk tidak ditemukan.'); end if;
  end if;
  return (select p from jsonb_array_elements(a3_products()->'products') p where (p->>'id')::bigint = pid);
end $$;

create or replace function a3_admin_product_del(p_id bigint) returns jsonb
language plpgsql security definer set search_path = public as $$
begin
  perform a3_admin();
  delete from products where id = p_id;
  return jsonb_build_object('message', 'ok');
end $$;

create or replace function a3_admin_size_save(p_id bigint, p_price integer, p_stock integer) returns jsonb
language plpgsql security definer set search_path = public as $$
declare s product_sizes;
begin
  perform a3_admin();
  update product_sizes set price = greatest(0, p_price), stock = greatest(0, p_stock) where id = p_id returning * into s;
  if not found then perform a3_err('Ukuran tidak ditemukan.'); end if;
  return to_jsonb(s);
end $$;

-- ---------- Hak akses fungsi ----------
do $$
declare f record;
begin
  for f in select p.oid::regprocedure as sig, p.proname from pg_proc p join pg_namespace n on n.oid = p.pronamespace
           where n.nspname = 'public' and p.proname like 'a3\_%' loop
    execute format('revoke all on function %s from public, anon, authenticated', f.sig);
