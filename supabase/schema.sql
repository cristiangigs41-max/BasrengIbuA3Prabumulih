create or replace function a3_admin_set_status(p_order bigint, p_status text) returns jsonb
language plpgsql security definer set search_path = public as $$
declare o orders; nxt text;
begin
  perform a3_admin();
  select * into o from orders where id = p_order for update;
  if not found then perform a3_err('Pesanan tidak ditemukan.'); end if;
  if p_status not in ('Pending','Diproses','Dikirim','Selesai','Dibatalkan') then perform a3_err('Status tidak valid.'); end if;
  if o.status = 'Dibatalkan' then perform a3_err('Pesanan yang dibatalkan tidak bisa dibuka kembali.'); end if;
  if o.status = 'Selesai' and p_status <> 'Selesai' then perform a3_err('Pesanan yang sudah selesai tidak bisa diubah.'); end if;
  nxt := case o.status when 'Pending' then 'Diproses' when 'Diproses' then 'Dikirim' when 'Dikirim' then 'Selesai' end;
  if p_status <> o.status and p_status <> 'Dibatalkan' and nxt is distinct from p_status then
    perform a3_err('Urutan status: Pending → Diproses → Dikirim → Selesai.');
  end if;
  if p_status = 'Selesai' and o.payment_method = 'COD (Bayar di Tempat)' and o.delivery_proof is null then
    perform a3_err('Pelanggan wajib mengunggah bukti pembayaran ke pengantar dulu.');
  end if;
  if p_status = 'Dibatalkan' then
    update product_sizes s set stock = s.stock + i.qty from order_items i where i.order_id = o.id and i.product_size_id = s.id;
  end if;
  update orders set status = p_status, payment_status = case when p_status = 'Selesai' then 'Dibayar' else payment_status end
  where id = o.id returning * into o;
  return a3_order_json(o);
end $$;

create or replace function a3_admin_customers() returns jsonb language plpgsql stable security definer set search_path = public as $$
