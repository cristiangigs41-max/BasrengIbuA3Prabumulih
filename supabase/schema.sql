create or replace function a3_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into profiles (id, name, email, phone, role)
  values (
    new.id,
    left(coalesce(nullif(trim(new.raw_user_meta_data->>'name'), ''), split_part(new.email, '@', 1)), 100),
    lower(new.email),
    left(new.raw_user_meta_data->>'phone', 20),
    case when exists (select 1 from a3_admin_emails a where a.email = lower(new.email)) then 'admin' else 'customer' end
  ) on conflict (id) do nothing;
  return new;
end $$;
drop trigger if exists a3_on_signup on auth.users;
create trigger a3_on_signup after insert on auth.users for each row execute function a3_new_user();

-- ---------- Helper ----------
create or replace function a3_err(msg text) returns void language plpgsql as $$
begin raise exception '%', msg using errcode = 'P0001'; end $$;

create or replace function a3_uid() returns uuid language plpgsql stable security definer set search_path = public as $$
declare u uuid := auth.uid();
begin
  if u is null or not exists (select 1 from profiles where id = u) then
    raise exception 'Silakan login terlebih dahulu.' using errcode = 'P0001';
  end if;
  return u;
end $$;

create or replace function a3_admin() returns uuid language plpgsql stable security definer set search_path = public as $$
declare u uuid := a3_uid();
begin
  if not exists (select 1 from profiles where id = u and role = 'admin') then
    raise exception 'Akses khusus admin.' using errcode = 'P0001';
  end if;
  return u;
end $$;

create or replace function a3_flavors() returns text[] language sql immutable as $$
  select array['Original','Original Daun Jeruk','Pedas','Pedas Daun Jeruk']
$$;

create or replace function a3_user_json(p profiles) returns jsonb language sql stable as $$
  select jsonb_build_object('id', p.id, 'name', p.name, 'email', p.email, 'phone', p.phone, 'role', p.role)
$$;

create or replace function a3_order_json(o orders) returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'id', o.id, 'code', o.code, 'status', o.status, 'total', o.total, 'phone', o.phone, 'address', o.address,
    'created_at', o.created_at, 'customer_id', o.user_id,
    'customer', (select p.name from profiles p where p.id = o.user_id),
    'payment_method', o.payment_method, 'payment_status', o.payment_status,
    'proof', o.proof, 'delivery_proof', o.delivery_proof, 'latitude', o.latitude, 'longitude', o.longitude,
    'items', coalesce((select jsonb_agg(jsonb_build_object(
        'product_size_id', i.product_size_id, 'product_name', i.product_name, 'size_label', i.size_label,
        'flavor', i.flavor, 'qty', i.qty, 'price', i.price, 'subtotal', i.subtotal) order by i.id)
      from order_items i where i.order_id = o.id), '[]'::jsonb))
$$;

create or replace function a3_cart_json(u uuid) returns jsonb language sql stable security definer set search_path = public as $$
  with it as (
    select c.id, c.product_size_id, c.flavor, c.qty, p.name as product_name, s.label as size_label, s.price, s.stock,
           s.price::bigint * c.qty as subtotal
    from cart_items c
    join product_sizes s on s.id = c.product_size_id
    join products p on p.id = s.product_id
    where c.user_id = u order by c.id)
  select jsonb_build_object(
    'items', coalesce((select jsonb_agg(to_jsonb(it)) from it), '[]'::jsonb),
    'total', coalesce((select sum(subtotal) from it), 0),
    'count', coalesce((select sum(qty) from it), 0))
$$;

