create or replace function a3_admin_stats() returns jsonb language plpgsql stable security definer set search_path = public as $$
declare d jsonb;
begin
  perform a3_admin();
  select jsonb_build_object(
    'products', (select count(*) from products),
    'customers', (select count(*) from profiles where role = 'customer'),
    'orders', (select count(*) from orders),
    'revenue', coalesce((select sum(total) from orders where status <> 'Dibatalkan'), 0),
    'sales', (select jsonb_agg(jsonb_build_object('date', to_char(x.g, 'YYYY-MM-DD'),
                'total', coalesce((select sum(o.total) from orders o where o.status <> 'Dibatalkan' and (o.created_at at time zone 'Asia/Jakarta')::date = x.g), 0)) order by x.g)
              from generate_series((now() at time zone 'Asia/Jakarta')::date - 6, (now() at time zone 'Asia/Jakarta')::date, interval '1 day') gs(g0), lateral (select g0::date as g) x),
    'latest', coalesce((select jsonb_agg(a3_order_json(x) order by x.id desc) from (select * from orders order by id desc limit 5) x), '[]'::jsonb),
    'top', coalesce((select jsonb_agg(jsonb_build_object('name', t.name, 'qty', t.qty) order by t.qty desc)
                     from (select i.product_name || ' ' || i.size_label as name, sum(i.qty)::int as qty
                           from order_items i join orders o on o.id = i.order_id where o.status <> 'Dibatalkan'
                           group by 1 order by 2 desc limit 5) t), '[]'::jsonb)
  ) into d;
  return d;
end $$;

