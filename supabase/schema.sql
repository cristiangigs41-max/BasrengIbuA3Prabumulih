create or replace function a3_me(p_name text default null, p_phone text default null) returns jsonb
language plpgsql security definer set search_path = public as $$
declare u uuid := a3_uid(); r profiles;
begin
  if p_name is not null then
    if length(trim(p_name)) < 3 then perform a3_err('Nama minimal 3 karakter.'); end if;
    update profiles set name = left(trim(p_name), 100), phone = left(p_phone, 20) where id = u;
  end if;
  select * into r from profiles where id = u;
  return a3_user_json(r);
end $$;

-- ---------- Keranjang ----------
create or replace function a3_cart() returns jsonb language plpgsql security definer set search_path = public as $$
begin return a3_cart_json(a3_uid()); end $$;

create or replace function a3_cart_add(p_size bigint, p_flavor text, p_qty integer) returns jsonb
language plpgsql security definer set search_path = public as $$
declare u uuid := a3_uid(); s product_sizes; pr products; have integer; want integer;
begin
  select * into s from product_sizes where id = p_size;
  if not found then perform a3_err('Produk tidak tersedia.'); end if;
  select * into pr from products where id = s.product_id;
  if not pr.is_active then perform a3_err('Produk tidak tersedia.'); end if;
  if not (p_flavor = any (a3_flavors())) then perform a3_err('Rasa tidak valid.'); end if;
  select qty into have from cart_items where user_id = u and product_size_id = p_size and flavor = p_flavor;
  want := coalesce(have, 0) + greatest(1, coalesce(p_qty, 1));
  if want > s.stock then perform a3_err('Stok tidak cukup.'); end if;
  insert into cart_items (user_id, product_size_id, flavor, qty) values (u, p_size, p_flavor, want)
  on conflict (user_id, product_size_id, flavor) do update set qty = excluded.qty;
  return a3_cart_json(u);
end $$;

create or replace function a3_cart_set(p_item bigint, p_qty integer) returns jsonb
language plpgsql security definer set search_path = public as $$
declare u uuid := a3_uid(); c cart_items; s product_sizes;
begin
  select * into c from cart_items where id = p_item and user_id = u;
  if not found then perform a3_err('Item tidak ditemukan.'); end if;
  select * into s from product_sizes where id = c.product_size_id;
  if p_qty > s.stock then perform a3_err('Stok tidak cukup.'); end if;
  update cart_items set qty = greatest(1, p_qty) where id = p_item;
  return a3_cart_json(u);
end $$;

create or replace function a3_cart_del(p_item bigint) returns jsonb
language plpgsql security definer set search_path = public as $$
declare u uuid := a3_uid();
begin
  delete from cart_items where id = p_item and user_id = u;
  return a3_cart_json(u);
end $$;

